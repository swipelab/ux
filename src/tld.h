// Whether `label` is one of kTlds or kIdnTlds as written, or com, edu, gov, net or org in any
// case: a capitalised word such as "It" is no TLD.
inline bool IsTld(std::u16string_view label) {
  constexpr std::u16string_view kAnyCase[] = {u"com", u"edu", u"gov", u"net", u"org"};
  const auto any_case = [label](std::u16string_view tld) {
    return std::equal(tld.begin(), tld.end(), label.begin(), label.end(),
                      [](char16_t t, char16_t c) { return t == c || t == c + (u'a' - u'A'); });
  };
  return std::binary_search(std::begin(kTlds), std::end(kTlds), label) ||
         std::binary_search(std::begin(kIdnTlds), std::end(kIdnTlds), label) ||
         std::any_of(std::begin(kAnyCase), std::end(kAnyCase), any_case);
}

