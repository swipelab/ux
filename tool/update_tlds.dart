// Generates lib/src/url/tld.dart, the TLDs the link detector reads, from the
// newest tool/url_data/tlds-<version>.txt.
//
//   dart run tool/update_tlds.dart          writes lib/src/url/tld.dart
//   dart run tool/update_tlds.dart --check  exits 1 where it differs
//   dart run tool/update_tlds.dart --update fetches IANA's current list
import 'dart:convert';
import 'dart:io';

const _output = 'lib/src/url/tld.dart';
const _iana = 'https://data.iana.org/TLD/tlds-alpha-by-domain.txt';

Future<void> main(List<String> args) async {
  final root = Directory.current.path;
  if (args.length == 1 && args[0] == '--update') {
    await _fetch(root);
  } else if (!(args.isEmpty || (args.length == 1 && args[0] == '--check'))) {
    stderr.writeln(
      'usage: dart run tool/update_tlds.dart [--check | --update]',
    );
    exit(2);
  }
  final input = _newest(root);
  final generated = generate(
    input.uri.pathSegments.last,
    input.readAsStringSync(),
  );
  final out = File('$root/$_output');
  if (args.isNotEmpty && args[0] == '--check') {
    if (!out.existsSync() || out.readAsStringSync() != generated) {
      stderr.writeln('$_output differs from its generation from ${input.path}');
      exit(1);
    }
    stdout.writeln('$_output matches its generation from ${input.path}');
    return;
  }
  out.writeAsStringSync(generated);
  stdout.writeln('wrote $_output from ${input.path}');
}

File _newest(String root) {
  final lists = [
    for (final f in Directory('$root/tool/url_data').listSync())
      if (f is File && RegExp(r'tlds-\d+\.txt$').hasMatch(f.path)) f,
  ]..sort((a, b) => a.path.compareTo(b.path));
  if (lists.isEmpty) {
    stderr.writeln('tool/url_data holds no tlds-<version>.txt');
    exit(1);
  }
  return lists.last;
}

Future<void> _fetch(String root) async {
  final client = HttpClient();
  try {
    final response = await (await client.getUrl(Uri.parse(_iana))).close();
    if (response.statusCode != 200) {
      stderr.writeln('$_iana: HTTP ${response.statusCode}');
      exit(1);
    }
    final body = await response.transform(utf8.decoder).join();
    final version = RegExp(r'^# Version (\d+)').firstMatch(body)?[1];
    if (version == null) {
      stderr.writeln('$_iana names no version');
      exit(1);
    }
    final entries = body
        .split('\n')
        .where((l) => l.isNotEmpty && !l.startsWith('#'));
    File('$root/tool/url_data/tlds-$version.txt').writeAsStringSync(
      '# Version $version of $_iana\n${entries.join('\n')}\n',
    );
    stdout.writeln('fetched version $version of $_iana');
  } finally {
    client.close();
  }
}

/// lib/src/url/tld.dart from [name], a TLD list whose text is [source]: one
/// entry per line, after '#' comment lines.
String generate(String name, String source) {
  final ascii = [
    for (final line in source.split('\n'))
      if (line.trim().isNotEmpty && !line.startsWith('#'))
        line.trim().toLowerCase(),
  ]..sort();
  final unicode = [
    for (final t in ascii)
      if (t.startsWith('xn--')) decodePunycode(t.substring(4)),
  ]..sort();
  final version = RegExp(r'tlds-(\d+)\.txt').firstMatch(name)![1];
  return [
    '// Generated by tool/update_tlds.dart from tool/url_data/$name,',
    '// version $version of IANA\'s tlds-alpha-by-domain.txt.',
    '',
    '/// Whether [label] is a TLD as written, in lowercase or as the Unicode',
    '/// label of an xn-- entry, or com, edu, gov, net or org in any case.',
    'bool isTld(String label) =>',
    '    _ascii.contains(label) ||',
    '    _unicode.contains(label) ||',
    "    const {'com', 'edu', 'gov', 'net', 'org'}.contains(label.toLowerCase());",
    '',
    '/// Whether [label] in lowercase is a TLD or the Unicode label of one.',
    'bool isTldInAnyCase(String label) {',
    '  final lower = label.toLowerCase();',
    '  return _ascii.contains(lower) || _unicode.contains(lower);',
    '}',
    '',
    "final _ascii = _asciiList.split(' ').toSet();",
    '',
    "final _unicode = _unicodeList.split(' ').toSet();",
    '',
    '/// The entries in lowercase, xn-- entries included.',
    _strings('_asciiList', ascii),
    '',
    '/// The Unicode labels of the xn-- entries.',
    _strings('_unicodeList', unicode),
    '',
  ].join('\n');
}

String _strings(String name, List<String> values) {
  String escape(String s) => s.runes
      .map(
        (cp) => cp < 0x80
            ? String.fromCharCode(cp)
            : '\\u{${cp.toRadixString(16).toUpperCase()}}',
      )
      .join();
  final lines = <String>[];
  var line = StringBuffer();
  for (var i = 0; i < values.length; i++) {
    final item = escape(values[i]) + (i + 1 < values.length ? ' ' : '');
    if (line.isNotEmpty && line.length + item.length > 74) {
      lines.add(line.toString());
      line = StringBuffer();
    }
    line.write(item);
  }
  lines.add(line.toString());
  return 'const $name =\n${lines.map((l) => "    '$l'").join('\n')};';
}

/// RFC 3492's decoding of the Punycode [input], the label after `xn--`.
String decodePunycode(String input) {
  const base = 36, tMin = 1, tMax = 26, skew = 38, damp = 700;
  final out = <int>[];
  final delimiter = input.lastIndexOf('-');
  if (delimiter > 0) out.addAll(input.substring(0, delimiter).codeUnits);
  var n = 128, i = 0, bias = 72;
  int digit(int c) =>
      c >= 0x30 && c <= 0x39 ? c - 0x30 + 26 : (c | 0x20) - 0x61;
  int adapt(int delta, int points, bool first) {
    delta = first ? delta ~/ damp : delta ~/ 2;
    delta += delta ~/ points;
    var k = 0;
    while (delta > ((base - tMin) * tMax) ~/ 2) {
      delta ~/= base - tMin;
      k += base;
    }
    return k + (base - tMin + 1) * delta ~/ (delta + skew);
  }

  var p = delimiter > 0 ? delimiter + 1 : 0;
  while (p < input.length) {
    final old = i;
    var w = 1;
    for (var k = base; ; k += base) {
      final d = digit(input.codeUnitAt(p++));
      i += d * w;
      final t = k <= bias ? tMin : (k >= bias + tMax ? tMax : k - bias);
      if (d < t) break;
      w *= base - t;
    }
    bias = adapt(i - old, out.length + 1, old == 0);
    n += i ~/ (out.length + 1);
    i %= out.length + 1;
    out.insert(i++, n);
  }
  return String.fromCharCodes(out);
}
